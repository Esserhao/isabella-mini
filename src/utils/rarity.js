// 稀有度：离线算出来的，不需要任何后端、不需要真实用户数据。
//
// 做法：对 12 香调的可能组合做 30 万次分层采样（稀疏 2-4 调 / 中等 5-7 调 / 满铺），
// 每个组合过一遍 computeRadarValues 得到 6 维向量，求出整个配方空间的
// 质心与各维标准差，再把「到质心的标准化欧氏距离」排序成 101 个分位断点。
//
// 为什么要标准化：6 个维度的量纲差得很远（深邃度均值 70.7，轻盈感 36.5），
// 直接算欧氏距离会被深邃度一个人主导，稀有度就变成「木质香有多重」了。
//
// 运行时只做一次 6 次减法 + 二分查找，零开销。
// 卡上那句话是数学真话：「在所有可能的配方里，这支属于罕见的前 X%」——
// 不是编的用户统计。冷启动期只有你一个用户，真实统计那个数字会很难看。
//
// 采样脚本参数：seed=42, N=300000（改了 computeRadarValues 的权重就要重算）
// ============================================================

const CENTROID = [38.26, 53.73, 43.84, 48.78, 70.71, 36.51]
