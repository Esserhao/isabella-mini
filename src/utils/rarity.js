// 距离 → 百分位（0 = 最靠近质心 = 最平庸，100 = 最偏离 = 最罕见）
function distToPercentile(d) {
  if (d <= Q[0]) return 0
  if (d >= Q[100]) return 100
  let lo = 0
  let hi = 100
  while (lo < hi) {
    const mid = (lo + hi) >> 1
    if (Q[mid] < d) lo = mid + 1
    else hi = mid
  }
  return lo
}

// 分档文案：只在真的稀有时才吹，平庸区间说实话（说实话比虚假鼓励可信）
const TIERS = [
  { min: 97, top: 3, label: '极罕见', line: '在所有可能的配方里，这支属于罕见的前 3%' },
  { min: 90, top: 10, label: '罕见', line: '在所有可能的配方里，这支属于少见的前 10%' },
  { min: 75, top: 25, label: '少见', line: '偏离常规的一支，前 25%' },
  { min: 45, top: 55, label: '均衡', line: '结构均衡的一支，没有走极端' },
  { min: 0, top: 100, label: '经典', line: '很稳的一支，靠近大多数人会调出的中心' }
]

// 主入口：传 computeRadarValues 的结果（6 个 0-100 的数）
export function getRarity(radarValues) {
  const v = Array.isArray(radarValues) ? radarValues : []
  if (v.length !== 6) {
    return { percentile: 0, top: 100, label: '经典', line: '', tierIndex: TIERS.length - 1 }
  }
  let s = 0
  for (let i = 0; i < 6; i++) {
    const z = ((Number(v[i]) || 0) - CENTROID[i]) / SIGMA[i]
    s += z * z
  }
  const p = distToPercentile(Math.sqrt(s))
  let idx = TIERS.length - 1
  for (let i = 0; i < TIERS.length; i++) {
    if (p >= TIERS[i].min) { idx = i; break }
  }
  const t = TIERS[idx]
  return { percentile: p, top: t.top, label: t.label, line: t.line, tierIndex: idx }
}

// 卡片 / 分享标题用的短标签，例：「罕见 · 前 10%」
export function rarityBadge(radarValues) {
  const r = getRarity(radarValues)
  return `${r.label} · 前 ${r.top}%`
}
